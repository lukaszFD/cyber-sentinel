-- ============================================
-- Cyber Intelligence Database Deployment — POSTGRES
-- Version: 1.1
-- ============================================
-- Runs against: postgres_db (pgvector/pgvector:pg16 + pg_cron, see
-- Dockerfile.postgres). Executed by playbook 04_3_db_postgres.yml as the
-- `postgres` superuser, connected to the `cyber_intelligence` database.
-- Fully idempotent — re-run on every deployment.
--
-- DEPLOYMENT MODEL:
--   This script does NOT create the database itself. `cyber_intelligence`
--   is created by the Postgres container on first init (POSTGRES_DB in
--   docker-compose-cyber-sentinel.yml, service postgres_db).
--
-- SCHEMA:
--   Everything lives in the dedicated `cyber_sentinel` schema instead of
--   `public`, because this Postgres instance may later host unrelated
--   applications and `public` is shared by every database user.
--   `ALTER ROLE ... SET search_path = cyber_sentinel, public` (Section 1)
--   keeps unqualified queries from the app role (log_processor.py, n8n,
--   ad-hoc pgAdmin) working. All DDL below is fully schema-qualified.
--
-- SCHEMA VERSIONING:
--   Plain, idempotent SQL files under config/postgres/, run in order by
--   playbook 04.3: this file, db_partitioning_retention.sql,
--   db_ai_pipeline.sql (then db_ai_config_editor.sql by playbook 04.5).
--
-- IDENTITY COLUMNS:
--   GENERATED BY DEFAULT AS IDENTITY (not ALWAYS) so data can be loaded
--   with explicit ids (restores, migrations).
--
-- PARTITIONING:
--   Postgres declarative partitioning must be declared at CREATE TABLE
--   time. dns_queries, network_events and threat_indicators are created
--   here as `PARTITION BY RANGE (...)` parents with NO partitions
--   attached. Partitions and the pg_cron retention jobs are created by
--   db_partitioning_retention.sql, which MUST run immediately after this
--   file — until then every INSERT into those tables is rejected.
--
-- FOREIGN KEYS:
--   A partitioned table can only be an FK TARGET when the referencing
--   columns match its full partition-key unique constraint. Outgoing
--   FKs from a partitioned table to a normal table are fine:
--     - threat_indicators.analysis_result_id -> ai_analysis_results(id)  REAL FK
--     - threat_indicators.type_id            -> dic_indicator_types(id)  REAL FK
--     - threat_indicators.dns_query_id       -> dns_queries(id)          app-layer only
--       (dns_queries is itself partitioned)
--
-- CREDENTIALS:
--   {{ postgres_user }} / {{ vault_postgres_password }} are the app role
--   used by n8n and dns_log_processor (all_servers.yml / encrypted
--   vault.yml), rendered by Ansible's template module.
-- ============================================

-- ============================================
-- SECTION 0: EXTENSIONS
-- ============================================

CREATE EXTENSION IF NOT EXISTS pg_cron;
CREATE EXTENSION IF NOT EXISTS vector;

-- ============================================
-- SECTION 1: SCHEMA + USER MANAGEMENT
-- ============================================

CREATE SCHEMA IF NOT EXISTS cyber_sentinel AUTHORIZATION postgres;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = '{{ postgres_user }}') THEN
CREATE ROLE "{{ postgres_user }}" LOGIN PASSWORD '{{ vault_postgres_password }}';
ELSE
        ALTER ROLE "{{ postgres_user }}" WITH PASSWORD '{{ vault_postgres_password }}';
END IF;
END
$$;

GRANT CONNECT ON DATABASE cyber_intelligence TO "{{ postgres_user }}";
GRANT USAGE, CREATE ON SCHEMA cyber_sentinel TO "{{ postgres_user }}";
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA cyber_sentinel TO "{{ postgres_user }}";
ALTER DEFAULT PRIVILEGES IN SCHEMA cyber_sentinel GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "{{ postgres_user }}";

-- Convenience, not a correctness requirement: lets already-shipped
-- unqualified queries (log_processor.py, ad-hoc pgAdmin queries) keep
-- working without prefixing every table with `cyber_sentinel.`.
ALTER ROLE "{{ postgres_user }}" SET search_path = cyber_sentinel, public;


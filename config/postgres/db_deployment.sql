CREATE TABLE IF NOT EXISTS cyber_sentinel.dns_queries (
                                                          id INT GENERATED BY DEFAULT AS IDENTITY,
                                                          timestamp TIMESTAMP NOT NULL,
                                                          query_type VARCHAR(10) NOT NULL,
    record_type VARCHAR(10),
    domain TEXT NOT NULL,
    source_ip VARCHAR(45) NOT NULL,
    response_ip VARCHAR(45),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id, timestamp)
    ) PARTITION BY RANGE (timestamp);

CREATE INDEX IF NOT EXISTS idx_id_dns ON cyber_sentinel.dns_queries (id);
CREATE INDEX IF NOT EXISTS idx_domain ON cyber_sentinel.dns_queries (domain);
CREATE INDEX IF NOT EXISTS idx_timestamp_dns ON cyber_sentinel.dns_queries (timestamp);
CREATE INDEX IF NOT EXISTS idx_source_ip_dns ON cyber_sentinel.dns_queries (source_ip);
CREATE INDEX IF NOT EXISTS idx_response_ip ON cyber_sentinel.dns_queries (response_ip);
CREATE INDEX IF NOT EXISTS idx_domain_timestamp ON cyber_sentinel.dns_queries (domain, timestamp);

CREATE TABLE IF NOT EXISTS cyber_sentinel.ai_analysis_results (
                                                                  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                                  threat_score INT NOT NULL,
                                                                  threat_label VARCHAR(50),
    verdict_summary_en TEXT,
    analysis_pl TEXT,
    confidence_score DECIMAL(5,2) DEFAULT NULL,
    analyzed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_threat_level_results
    FOREIGN KEY (threat_score)
    REFERENCES cyber_sentinel.dic_threat_levels(score)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
    );
CREATE INDEX IF NOT EXISTS idx_threat_score ON cyber_sentinel.ai_analysis_results (threat_score);
CREATE INDEX IF NOT EXISTS idx_analyzed_at ON cyber_sentinel.ai_analysis_results (analyzed_at);

CREATE TABLE IF NOT EXISTS cyber_sentinel.threat_indicators (
                                                                id INT GENERATED BY DEFAULT AS IDENTITY,
                                                                dns_query_id INT NOT NULL,
                                                                type_id INT NOT NULL,
                                                                analysis_result_id INT NOT NULL,
                                                                last_scan TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                                                scan_count INT DEFAULT 1,
                                                                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                                                PRIMARY KEY (id, last_scan),
    CONSTRAINT uk_dns_analysis_scan UNIQUE (dns_query_id, analysis_result_id, last_scan),
    CONSTRAINT fk_indicator_type
    FOREIGN KEY (type_id)
    REFERENCES cyber_sentinel.dic_indicator_types(id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    CONSTRAINT fk_indicator_analysis_result
    FOREIGN KEY (analysis_result_id)
    REFERENCES cyber_sentinel.ai_analysis_results(id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
    ) PARTITION BY RANGE (last_scan);

CREATE INDEX IF NOT EXISTS idx_id_ti ON cyber_sentinel.threat_indicators (id);
CREATE INDEX IF NOT EXISTS idx_dns_query ON cyber_sentinel.threat_indicators (dns_query_id);
CREATE INDEX IF NOT EXISTS idx_last_scan ON cyber_sentinel.threat_indicators (last_scan);
CREATE INDEX IF NOT EXISTS idx_type ON cyber_sentinel.threat_indicators (type_id);

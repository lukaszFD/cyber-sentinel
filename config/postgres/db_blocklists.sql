--   A domain covered by an active MANUAL allow-list entry (the domain or a
--   parent) is never published. Tranco entries and trusted infrastructure
--   do NOT protect: telemetry usually sits on popular vendor domains.
--   Rejected entries stay in the table, so the same domain is not proposed
--   again.
--
-- Domains only, exact match: Pi-hole does not block IPs, and an entry does
-- not cover subdomains.

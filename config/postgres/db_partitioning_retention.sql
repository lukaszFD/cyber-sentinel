-- ============================================
-- DATA RETENTION STRATEGY — POSTGRES
-- Cyber Intelligence System — Postgres port
-- ============================================
-- Strategy: Monthly declarative partitioning, 6-month retention
-- Tables: cyber_sentinel.dns_queries, cyber_sentinel.network_events,
--         cyber_sentinel.threat_indicators
-- Automation: pg_cron (replaces MySQL Event Scheduler)
--
-- PREREQUISITES:
--   1. Run db_deployment.sql FIRST — the parent tables must already exist
--      in the cyber_sentinel schema as PARTITION BY RANGE tables with zero
--      partitions attached.
--   2. pg_cron extension must be enabled (done in db_deployment.sql,
--      Section 0) with shared_preload_libraries='pg_cron' active on the
--      Postgres container.
--
-- PARTITION NAMING:
--   MySQL partition names were local to each table (p202609 could exist
--   independently on dns_queries, network_events, and threat_indicators).
--   Postgres partitions are ordinary tables in the same schema, so
--   identical names across tables would still collide even within
--   cyber_sentinel. Names here are `<table>_p<YYYYMM>`
--   (e.g. cyber_sentinel.dns_queries_p202609).
--
-- SCHEMA SCOPING:
--   Every pg_class / pg_namespace lookup below filters on
--   n.nspname = 'cyber_sentinel' (or the equivalent join) — this matters
--   now more than it did under `public`, since other future applications
--   may have their own same-named partition maintenance objects in their
--   own schemas, and these functions must never touch them.
-- ============================================

-- ============================================
-- PART 1: MAINTENANCE LOG TABLE (same name/shape as MySQL)
-- ============================================
CREATE TABLE IF NOT EXISTS cyber_sentinel.partition_maintenance_log (
                                                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                                        table_name VARCHAR(100) NOT NULL,
    partition_name VARCHAR(100) NOT NULL,
    action VARCHAR(20) NOT NULL,
    error_message TEXT,
    executed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    );
CREATE INDEX IF NOT EXISTS idx_executed_at ON cyber_sentinel.partition_maintenance_log (executed_at);
CREATE INDEX IF NOT EXISTS idx_table_name_log ON cyber_sentinel.partition_maintenance_log (table_name);

